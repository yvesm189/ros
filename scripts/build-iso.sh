#!/usr/bin/env bash
# Build a bootable ROS ISO.
#
# live-build needs a privileged Linux environment with loop devices, so on a
# Mac (or any non-Debian host) this runs inside a container. Everything it
# needs is installed in that container; nothing is installed on the host.
#
#   ./scripts/build-iso.sh                 # amd64, the deployment target
#   ARCH=arm64 ./scripts/build-iso.sh      # native and much faster on Apple silicon
#
# Note on Apple silicon: an amd64 build runs under emulation and takes hours.
# Build arm64 while iterating on the desktop, and amd64 when you need the
# image a real office PC will boot.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VERSION="$(cat "${ROOT}/VERSION")"
ARCH="${ARCH:-amd64}"
SUITE="${SUITE:-trixie}"
CODENAME="${CODENAME:-inzira}"
LB_DIR="${ROOT}/base/live-build"
OUT="${ROOT}/out"
IMAGE="${ROS_BUILDER_IMAGE:-debian:trixie}"

BUILD_DEPS="live-build debootstrap squashfs-tools xorriso dosfstools mtools \
ca-certificates rsync apt-utils cpio file"
case "${ARCH}" in
    amd64) BUILD_DEPS="${BUILD_DEPS} syslinux syslinux-common isolinux grub-efi-amd64-bin grub-common" ;;
    arm64) BUILD_DEPS="${BUILD_DEPS} grub-efi-arm64-bin grub-common" ;;
    *) echo "error: unsupported ARCH '${ARCH}'" >&2; exit 1 ;;
esac

echo ">> ROS ${VERSION} (${CODENAME}) - ${SUITE}/${ARCH}"

# 1. The ROS packages go into the image as locally built .debs. live-build
#    installs everything it finds in config/packages.chroot automatically.
echo ">> building ROS packages"
"${ROOT}/scripts/build-debs.sh" >/dev/null
mkdir -p "${LB_DIR}/config/packages.chroot"
rm -f "${LB_DIR}/config/packages.chroot"/*.deb
cp "${OUT}/packages"/*.deb "${LB_DIR}/config/packages.chroot/"

# 2. Stamp the release so the in-chroot branding hook knows what it is building.
mkdir -p "${LB_DIR}/config/includes.chroot/etc/ros"
cat > "${LB_DIR}/config/includes.chroot/etc/ros/release" <<RELEASE
# Generated by scripts/build-iso.sh - do not edit.
ROS_VERSION=${VERSION}
ROS_CODENAME=${CODENAME}
ROS_BUILD_DATE=$(date -u +%Y-%m-%dT%H:%M:%SZ)
ROS_SUITE=${SUITE}
ROS_ARCH=${ARCH}
RELEASE

mkdir -p "${OUT}"

# 3. Run live-build.
if command -v lb >/dev/null 2>&1 && [ "$(uname -s)" = "Linux" ]; then
    RUNNER="native"
else
    RUNNER="docker"
fi

if [ "${RUNNER}" = "docker" ]; then
    command -v docker >/dev/null 2>&1 || { echo "error: docker is required on this host" >&2; exit 1; }
    echo ">> building in ${IMAGE} (linux/${ARCH})"
    docker run --rm --privileged \
        --platform "linux/${ARCH}" \
        -v "${ROOT}:/ros" \
        -w /ros/base/live-build \
        -e ROS_VERSION="${VERSION}" \
        -e ROS_CODENAME="${CODENAME}" \
        -e ROS_ARCH="${ARCH}" \
        -e ROS_SUITE="${SUITE}" \
        "${IMAGE}" \
        bash -eux -c "
            export DEBIAN_FRONTEND=noninteractive
            apt-get update
            apt-get install -y --no-install-recommends ${BUILD_DEPS}
            lb clean --purge || true
            lb config
            lb build
            mkdir -p /ros/out
            cp -v *.iso /ros/out/ 2>/dev/null || cp -v *.img /ros/out/
            chmod -R a+rw /ros/out
        "
else
    echo ">> building natively"
    ( cd "${LB_DIR}" \
        && ROS_VERSION="${VERSION}" ROS_CODENAME="${CODENAME}" ROS_ARCH="${ARCH}" ROS_SUITE="${SUITE}" \
           bash -c "lb clean --purge || true; lb config; lb build" \
        && cp -v ./*.iso "${OUT}/" )
fi

# 4. Checksum whatever came out.
cd "${OUT}"
for image in ros-*.iso; do
    [ -e "${image}" ] || continue
    shasum -a 256 "${image}" > "${image}.sha256" 2>/dev/null \
        || sha256sum "${image}" > "${image}.sha256"
    echo
    echo ">> ${OUT}/${image}"
    cat "${image}.sha256"
done
